function normalizeFormIndex(index) {
  const total = RAW_FORMS.length;
  const raw = Number(index) || 0;
  return ((raw % total) + total) % total;
}

export { DEFAULT_PALETTE };

export const FORMS = RAW_FORMS.map((form) => ({
  ...form,
  baseGrid: toGrid(form.baseRows),
  frames: form.frames.map((frame) => ({
    hold: frame.hold,
    grid: toGrid(frame.rows)
  })),
  palette: form.palette ? Object.freeze({ ...DEFAULT_PALETTE, ...form.palette }) : null
}));

export const FORM_NAMES = FORMS.map((form) => form.label);
export const SPECIAL_PALETTE_FORM_IDS = FORMS.filter((form) => form.palette).map((form) => form.id);

export function getForm(index = 0) {
  return FORMS[normalizeFormIndex(index)];
}

export function getFormName(index = 0) {
  return getForm(index).label;
}

export function getFormFrame(index = 0, frameIndex = 0) {
  const form = getForm(index);
  const normalizedFrameIndex = ((Number(frameIndex) || 0) % form.frames.length + form.frames.length) % form.frames.length;
  return form.frames[normalizedFrameIndex];
}

export function getPaletteForForm(index = 0) {
  return getForm(index).palette ?? DEFAULT_PALETTE;
}
